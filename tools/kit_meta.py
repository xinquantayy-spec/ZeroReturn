#!/usr/bin/env python3
"""Generate src/shared/KitMeta.luau from the Blender kit exports (assets/exports/<batch>.meta.json + .props.json).
Each kit prop is split into material pieces ZR_MK_<Prop>__<mat> that share one origin; KitMeta lists, per prop, its
whole bounding box (Roblox space, from the origin) and each piece's centre offset (the MeshPart pivot is its own
bounding-box centre, so a piece goes to origin * CFrame.new(center)).
Merged pieces (art-5b phase 2): where a batch's merged export is present (assets/exports/<batch>M.{meta,props}.json,
from zr_kit.kit_export_merged), its props also get `merged`: the one mesh ZR_MK_<Prop>__<mat>_M that joins the pieces
listed in `of` (Maps/Kit.luau places it when Kit.MERGE[batch] is on). Without merged exports the output is what it was.
Usage: python3 tools/kit_meta.py ZR_MallKitA ZR_MallKitB ZR_MallKitC
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def v(a):
    return "V(%s)" % ", ".join(("%.4f" % x).rstrip("0").rstrip(".") if abs(x) > 1e-9 else "0" for x in a)


def merged_of(b, pj):
    """<batch>M's joined piece per prop: (mat, center, tris, of), or {} when the merged export is not there"""
    mp, pp = (os.path.join(ROOT, "assets", "exports", b + "M" + ext) for ext in (".meta.json", ".props.json"))
    if not (os.path.exists(mp) and os.path.exists(pp)):
        return {}
    meta, mj = json.load(open(mp)), json.load(open(pp))
    out = {}
    for name, r in mj.items():
        if name not in pj or not set(r["of"]) <= set(pj[name]["mats"]) or len(r["of"]) < 2:
            raise SystemExit("%sM: %s joins %s, not two or more of its pieces %s: export the batch and its merged batch "
                             "from the same build" % (b, name, r["of"], pj.get(name, {}).get("mats")))
        m = meta["ZR_MK_%s__%s_M" % (name, r["mat"])]
        out[name] = (r["mat"], m["center"], m.get("tris", 0), list(r["of"]))
    return out


def main(batches):
    props, merged, mbatches = {}, {}, []
    for b in batches:
        meta = json.load(open(os.path.join(ROOT, "assets", "exports", b + ".meta.json")))
        pj = json.load(open(os.path.join(ROOT, "assets", "exports", b + ".props.json")))
        for name, p in pj.items():
            if name in props:  # piece MeshParts are looked up by name, so a clash would swap meshes between kits
                raise SystemExit("kit prop %s is in both %s and %s: rename one in its build script" % (name, props[name][0], b))
            pieces = []
            for mat in p["mats"]:
                key = "ZR_MK_%s__%s" % (name, mat)
                m = meta[key]
                pieces.append((mat, m["center"], m.get("tris", 0)))
            props[name] = (b, p["size"], p["center"], pieces)
        mg = merged_of(b, pj)
        if mg:
            merged.update(mg)
            mbatches.append(b + "M")
    out = ["--!strict",
           "-- Generated by tools/kit_meta.py from assets/exports/%s.{meta,props}.json. Do not edit by hand." % "|".join(batches),
           "-- props[name] = { batch, size, center (whole prop bounding box, Roblox space, from the prop origin), pieces = {",
           "--   { mat, center (that piece's bounding-box centre from the origin), tris } } }. Piece MeshParts are named",
           "-- ZR_MK_<name>__<mat> in ReplicatedStorage.ZR_Assets."]
    if merged:
        out += ["-- merged = { mat, center, tris, of }: the opaque pieces `of` joined into one mesh ZR_MK_<name>__<mat>_M (art-5b",
                "-- phase 2, from %s; placed when Maps/Kit.luau's Kit.MERGE[batch] is on)." % "|".join(mbatches)]
    out += ["local V = Vector3.new",
           "return {",
           "\tprops = {"]
    for name in sorted(props):
        b, size, center, pieces = props[name]
        ps = ", ".join('{ mat = "%s", center = %s, tris = %d }' % (m, v(c), t) for m, c, t in pieces)
        mg = ""
        if name in merged:
            mm, mc, mt, of = merged[name]
            mg = ', merged = { mat = "%s", center = %s, tris = %d, of = { %s } }' % (mm, v(mc), mt, ", ".join('"%s"' % x for x in of))
        out.append('\t\t%s = { batch = "%s", size = %s, center = %s, pieces = { %s }%s },' % (name, b, v(size), v(center), ps, mg))
    out.append("\t},")
    out.append("}")
    path = os.path.join(ROOT, "src", "shared", "KitMeta.luau")
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote %s %d props %d pieces%s" % (path, len(props), sum(len(p[3]) for p in props.values()),
                                              (" (%d merged)" % len(merged)) if merged else ""))


if __name__ == "__main__":
    main(sys.argv[1:] or ["ZR_MallKitA", "ZR_MallKitB", "ZR_MallKitC"])
