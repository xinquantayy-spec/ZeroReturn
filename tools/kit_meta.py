#!/usr/bin/env python3
"""Generate src/shared/KitMeta.luau from the Blender kit exports (assets/exports/<batch>.meta.json + .props.json).
Each kit prop is split into material pieces ZR_MK_<Prop>__<mat> that share one origin; KitMeta lists, per prop, its
whole bounding box (Roblox space, from the origin) and each piece's centre offset (the MeshPart pivot is its own
bounding-box centre, so a piece goes to origin * CFrame.new(center)).
Usage: python3 tools/kit_meta.py ZR_MallKitA ZR_MallKitB ZR_MallKitC
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def v(a):
    return "V(%s)" % ", ".join(("%.4f" % x).rstrip("0").rstrip(".") if abs(x) > 1e-9 else "0" for x in a)


def main(batches):
    props = {}
    for b in batches:
        meta = json.load(open(os.path.join(ROOT, "assets", "exports", b + ".meta.json")))
        pj = json.load(open(os.path.join(ROOT, "assets", "exports", b + ".props.json")))
        for name, p in pj.items():
            if name in props:  # piece MeshParts are looked up by name, so a clash would swap meshes between kits
                raise SystemExit("kit prop %s is in both %s and %s: rename one in its build script" % (name, props[name][0], b))
            pieces = []
            for mat in p["mats"]:
                key = "ZR_MK_%s__%s" % (name, mat)
                m = meta[key]
                pieces.append((mat, m["center"], m.get("tris", 0)))
            props[name] = (b, p["size"], p["center"], pieces)
    out = ["--!strict",
           "-- Generated by tools/kit_meta.py from assets/exports/%s.{meta,props}.json. Do not edit by hand." % "|".join(batches),
           "-- props[name] = { batch, size, center (whole prop bounding box, Roblox space, from the prop origin), pieces = {",
           "--   { mat, center (that piece's bounding-box centre from the origin), tris } } }. Piece MeshParts are named",
           "-- ZR_MK_<name>__<mat> in ReplicatedStorage.ZR_Assets.",
           "local V = Vector3.new",
           "return {",
           "\tprops = {"]
    for name in sorted(props):
        b, size, center, pieces = props[name]
        ps = ", ".join('{ mat = "%s", center = %s, tris = %d }' % (m, v(c), t) for m, c, t in pieces)
        out.append('\t\t%s = { batch = "%s", size = %s, center = %s, pieces = { %s } },' % (name, b, v(size), v(center), ps))
    out.append("\t},")
    out.append("}")
    path = os.path.join(ROOT, "src", "shared", "KitMeta.luau")
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote", path, len(props), "props", sum(len(p[3]) for p in props.values()), "pieces")


if __name__ == "__main__":
    main(sys.argv[1:] or ["ZR_MallKitA", "ZR_MallKitB", "ZR_MallKitC"])
