#!/usr/bin/env python3
"""art-4b: write each gun or worn-gear texture sheet's SurfaceAppearance (src/shared/ZR_GunSA/<sheet>.model.json, synced by Rojo:
a game script cannot set a SurfaceAppearance's maps) and src/shared/GunTex.luau (piece -> sheet) from
assets/exports/<batch>.tex.json (zr_tex.export) and assets/textures/guns/images.json
({sheet: {"col": imageId, "nrm": ..., "rgh": ..., "mtl": ...}}, the uploaded decals' image ids).

A sheet without all four image ids is left out, so its pieces stay as they were rather than wearing a half-loaded set.
Only batches exported by zr_tex (with UVs) have a .tex.json: list their new model ids in AssetIds in the same commit.

    python3 tools/gun_tex.py                 # regenerate from the records
    python3 tools/gun_tex.py SHEET col=ID nrm=ID rgh=ID mtl=ID   # record a sheet's image ids first
"""
import glob, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXP = os.path.join(ROOT, "assets", "exports")
IMG = os.path.join(ROOT, "assets", "textures", "guns", "images.json")
SA_DIR = os.path.join(ROOT, "src", "shared", "ZR_GunSA")
OUT = os.path.join(ROOT, "src", "shared", "GunTex.luau")
MAPS = (("col", "ColorMap"), ("nrm", "NormalMap"), ("rgh", "RoughnessMap"), ("mtl", "MetalnessMap"))


def load_images():
    if os.path.exists(IMG):
        with open(IMG) as f:
            return json.load(f)
    return {}


def record(sheet, pairs):
    images = load_images()
    e = images.setdefault(sheet, {})
    for p in pairs:
        k, v = p.split("=", 1)
        assert k in dict(MAPS), k
        assert v.isdigit(), v
        e[k] = v
    os.makedirs(os.path.dirname(IMG), exist_ok=True)
    with open(IMG, "w") as f:
        json.dump(images, f, indent=1, sort_keys=True)


def main():
    if len(sys.argv) > 2:
        record(sys.argv[1], sys.argv[2:])
    images = load_images()
    pieces, sheets, skipped = {}, [], []
    os.makedirs(SA_DIR, exist_ok=True)
    for path in sorted(glob.glob(os.path.join(EXP, "*.tex.json"))):
        with open(path) as f:
            rec = json.load(f)
        for sheet, objs in sorted(rec["sheets"].items()):
            ids = images.get(sheet, {})
            if not all(ids.get(k) for k, _ in MAPS):
                skipped.append(sheet)
                continue
            sheets.append(sheet)
            props = {prop: "rbxassetid://%s" % ids[k] for k, prop in MAPS}
            with open(os.path.join(SA_DIR, sheet + ".model.json"), "w") as f:
                json.dump({"className": "SurfaceAppearance", "properties": props}, f, indent=2)
                f.write("\n")
            for o in objs:
                pieces[o] = sheet
    for f in glob.glob(os.path.join(SA_DIR, "*.model.json")):
        if os.path.basename(f)[: -len(".model.json")] not in sheets:
            os.remove(f)
    lines = [
        "--!strict",
        "-- GENERATED by tools/gun_tex.py from assets/exports/<batch>.tex.json and assets/textures/guns/images.json; do not edit.",
        "-- art-4b: which texture sheet (a SurfaceAppearance in ReplicatedStorage.ZR.ZR_GunSA) each textured piece wears: gun parts",
        "-- (zr_tex.py) and worn gear (zr_gtex.py, sheets ZR_GR_*; the game sets its Color to the item's tint).",
        "local M = {}",
        "M.pieces = {",
    ]
    for k in sorted(pieces):
        lines.append('\t["%s"] = "%s",' % (k, pieces[k]))
    lines += ["} :: { [string]: string }", "return M", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("GunTex.luau: %d pieces on %d sheets%s" % (len(pieces), len(sheets), ("; waiting for images: " + ", ".join(skipped)) if skipped else ""))


if __name__ == "__main__":
    main()
