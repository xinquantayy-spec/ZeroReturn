#!/usr/bin/env python3
"""Generate src/shared/GunMeta.luau (M14 weapon modding) from the Blender gun pipeline outputs:

  assets/exports/ZR_Guns.parts.json   part records (zr_guns.export_family / write_records): pieces, slots,
                                      anchors, 2D extents, tris, batch; and the preset builds
  assets/renders/guns/sprites.json    side-view sprites (zr_guns.pack_sprites): sheet, rectangle, origin pixel

Usage: python3 tools/gun_meta.py <image id of sprite sheet 0> [<image id of sheet 1> ...]

Coordinates are converted from Blender (x left, y toward the stock, z up; studs) to Roblox (x right, y up, z toward
the stock): (x, y, z) -> (-x, z, y). Slot rotations are Blender XYZ Euler degrees; the rotation matrix becomes
C * R * C^T with C the axis change above.
"""
import json, math, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
parts_json = json.loads((ROOT / "assets/exports/ZR_Guns.parts.json").read_text())
sprites_json = json.loads((ROOT / "assets/renders/guns/sprites.json").read_text())
ids = sys.argv[1:]
assert len(ids) == len(sprites_json["sheets"]), "one image id per sprite sheet: %s" % sprites_json["sheets"]

C = [[-1, 0, 0], [0, 0, 1], [0, 1, 0]]


def mm(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def tr(a):
    return [[a[j][i] for j in range(3)] for i in range(3)]


def euler_xyz(rx, ry, rz):
    cx, sx = math.cos(math.radians(rx)), math.sin(math.radians(rx))
    cy, sy = math.cos(math.radians(ry)), math.sin(math.radians(ry))
    cz, sz = math.cos(math.radians(rz)), math.sin(math.radians(rz))
    Rx = [[1, 0, 0], [0, cx, -sx], [0, sx, cx]]
    Ry = [[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]]
    Rz = [[cz, -sz, 0], [sz, cz, 0], [0, 0, 1]]
    return mm(Rz, mm(Ry, Rx))


def num(x, nd=5):
    v = round(float(x), nd)
    if v == 0:
        return "0"
    s = ("%." + str(nd) + "f") % v
    s = s.rstrip("0").rstrip(".")
    return s


def V(t):
    return "V(%s)" % ", ".join(num(x) for x in t)


def CF(pos, rot):
    # rot: record [bx, bz, by] (Blender X, Z, Y Euler degrees)
    bx, bz, by = rot
    if abs(bx) < 1e-9 and abs(by) < 1e-9 and abs(bz) < 1e-9:
        return "CF(%s)" % ", ".join(num(x) for x in pos)
    Rb = euler_xyz(bx, by, bz)
    Rr = mm(C, mm(Rb, tr(C)))
    vals = list(pos) + [Rr[i][j] for i in range(3) for j in range(3)]
    return "CF(%s)" % ", ".join(num(x, 6) for x in vals)


def tree_lua(t):
    kids = ", ".join("%s = %s" % (k, tree_lua(v)) for k, v in sorted(t["mods"].items()))
    return '{ "%s", { %s } }' % (t["id"], kids) if kids else '{ "%s", {} }' % t["id"]


lines = [
    "--!strict",
    "-- Generated by tools/gun_meta.py from assets/exports/ZR_Guns.parts.json and assets/renders/guns/sprites.json.",
    "-- Do not edit by hand. M14 weapon modding (docs/weapons/WEAPON_MODDING.md): the geometry of every gun part.",
    "--   parts[id] = { batch, cls (picture class), fam, tris, pieces = { { mesh name, material key, centre, sub? } },",
    "--                 slots = { name = CFrame of the child's origin in this part's frame },",
    "--                 anchors = { name = position }, ext = { zmin, zmax, ymin, ymax } (side-view extent) }",
    "--   Roblox studs, origin = where the part attaches; the gun points along -Z, +Y up.",
    "--   sprites[\"<id>@<cls>[@L]\"] = { sheet, x, y, w, h, ox, oy }: side-view picture at classes[cls] cells per",
    "--   metre and `cell` pixels per cell, (ox, oy) = the part origin's pixel; \"@L\" = turned onto a side rail.",
    "--   presets[id] = { base, tree = { part, { slot = subtree } } }",
    "local V = Vector3.new",
    "local CF = CFrame.new",
    "return {",
    "\tU = 3.125,",
    "\tcell = %d," % sprites_json["cell"],
    "\tclasses = { %s }," % ", ".join("%s = %s" % (k, num(v)) for k, v in sorted(sprites_json["classes"].items())),
    "\tsheets = { %s }," % ", ".join('"rbxassetid://%s"' % i for i in ids),
    "\tparts = {",
]
for pid in sorted(parts_json["parts"]):
    p = parts_json["parts"][pid]
    pieces = []
    for name in sorted(p["pieces"]):
        pc = p["pieces"][name]
        s = '{ "%s", "%s", %s' % (name, pc["mat"], V(pc["center"]))
        if pc.get("sub"):
            s += ', "%s"' % pc["sub"]
        pieces.append(s + " }")
    slots = ", ".join("%s = %s" % (k, CF(v["pos"], v["rot"])) for k, v in sorted(p["slots"].items()))
    anchors = ", ".join("%s = %s" % (k, V(v)) for k, v in sorted(p["anchors"].items()))
    ext = p["ext"]  # Blender [y min, y max, z min, z max] = Roblox [z min, z max, y min, y max]
    fam = ('"%s"' % p["family"]) if p.get("family") else "nil"
    lines.append('\t\t%s = { batch = "%s", cls = "%s", fam = %s, tris = %d,' % (pid, p["batch"], p["cls"], fam, p["tris"]))
    lines.append("\t\t\tpieces = { %s }," % ", ".join(pieces))
    lines.append("\t\t\tslots = { %s }," % slots)
    lines.append("\t\t\tanchors = { %s }," % anchors)
    lines.append("\t\t\text = { %s } }," % ", ".join(num(x) for x in ext))
lines.append("\t},")
lines.append("\tsprites = {")
for name in sorted(sprites_json["sprites"]):
    s = sprites_json["sprites"][name]
    lines.append('\t\t["%s"] = { %d, %d, %d, %d, %d, %s, %s },' % (name, s["sheet"] + 1, s["x"], s["y"], s["w"], s["h"], num(s["ox"], 2), num(s["oy"], 2)))
lines.append("\t},")
lines.append("\tpresets = {")
for pid in sorted(parts_json["presets"]):
    pr = parts_json["presets"][pid]
    lines.append('\t\t%s = { base = "%s", tree = %s },' % (pid, pr["base"], tree_lua(pr["tree"])))
lines += ["\t},", "}", ""]
out = ROOT / "src/shared/GunMeta.luau"
out.write_text("\n".join(lines))
print("GunMeta.luau: %d parts, %d sprites, %d presets, %d bytes" % (len(parts_json["parts"]), len(sprites_json["sprites"]), len(parts_json["presets"]), out.stat().st_size))
