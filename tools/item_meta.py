#!/usr/bin/env python3
"""Generate src/shared/ItemMeta.luau from assets/exports/ZR_Items{A,B,C}.{meta,mats}.json (build_items_export.py).
items[id] = { batch, size, center (whole item, Roblox space, from its origin), pieces = { { mat, center } } }
Piece MeshParts are named ZR_IT_<id>__<mat> in ReplicatedStorage.ZR_Assets."""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
items = {}
for batch in ("ZR_ItemsA", "ZR_ItemsB", "ZR_ItemsC"):
    meta = json.loads((ROOT / "assets/exports" / (batch + ".meta.json")).read_text())
    mats = json.loads((ROOT / "assets/exports" / (batch + ".mats.json")).read_text())
    for name, m in meta.items():
        iid, mat = name[len("ZR_IT_"):].rsplit("__", 1)
        assert mats[name] == mat, name
        e = items.setdefault(iid, {"batch": batch, "pieces": [], "lo": [1e9] * 3, "hi": [-1e9] * 3, "tris": 0})
        c, s = m["center"], m["size"]
        e["pieces"].append((mat, c))
        e["tris"] += m["tris"]
        for k in range(3):
            e["lo"][k] = min(e["lo"][k], c[k] - s[k] / 2)
            e["hi"][k] = max(e["hi"][k], c[k] + s[k] / 2)

def v(t):
    return "V(%s)" % ", ".join(("%.4f" % x).rstrip("0").rstrip(".") if x else "0" for x in t)

lines = [
    "--!strict",
    "-- Generated by tools/item_meta.py from assets/exports/ZR_Items{A,B,C}.{meta,mats}.json. Do not edit by hand.",
    "-- Loose loot models (build_items_export.py): items[id] = { batch, size, center, tris, pieces = { { mat, center } } };",
    "-- piece MeshParts are ZR_IT_<id>__<mat> in ReplicatedStorage.ZR_Assets, origin at the item's bottom centre.",
    "local V = Vector3.new",
    "return {",
]
for iid in sorted(items):
    e = items[iid]
    size = [e["hi"][k] - e["lo"][k] for k in range(3)]
    center = [(e["hi"][k] + e["lo"][k]) / 2 for k in range(3)]
    pcs = ", ".join('{ "%s", %s }' % (mat, v(c)) for mat, c in sorted(e["pieces"]))
    lines.append('\t%s = { batch = "%s", size = %s, center = %s, tris = %d, pieces = { %s } },' % (iid, e["batch"], v(size), v(center), e["tris"], pcs))
lines += ["}", ""]
(ROOT / "src/shared/ItemMeta.luau").write_text("\n".join(lines))
print("ItemMeta.luau:", len(items), "items,", sum(len(e["pieces"]) for e in items.values()), "pieces")
