def hand(b, s, side):
    w, h, d = s
    b.rbox((0, h * 0.18, 0), (w * 0.9, h * 0.56, d * 0.86), GLOVE, bevel=0.04)       # palm
    b.rbox((0, -h * 0.28, -d * 0.06), (w * 0.82, h * 0.42, d * 0.74), GLOVE2, bevel=0.03)  # fingers
