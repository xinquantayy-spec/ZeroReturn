BALA, SKIN, EYES = hexc("25272A"), hexc("8A6A55"), hexc("121314")
GLOVE, GLOVE2 = hexc("1D1E1D"), hexc("2A2C2A")
SOLE, BOOT, BOOT2 = hexc("19171A"), hexc("4A3F33"), hexc("3A3229")
BASE, MID, DARK, DEEP = grey(0.86), grey(0.7), grey(0.5), grey(0.34)


def B(x, y, z):
    """Roblox (x, y, z) -> Blender coordinates."""
    return (-x, z, y)


def BS(sx, sy, sz):
    return (sx, sz, sy)


class Seg(Builder):
    """Builder working in Roblox axes (x right, y up, z back)."""

    def rbox(self, c, s, color, bevel=0.0):
        self.box(B(*c), BS(*s), color, bevel=bevel)

    def rcyl(self, a, b, r1, color, r2=None, seg=10, smooth=True):
        self.cyl(B(*a), B(*b), r1, color, r2=r2, seg=seg, smooth=smooth)

    def fit(self, size):
        """scale/translate so the bounding box is exactly `size` (Roblox axes) and centred at the origin"""
        vs = self.bm.verts
        lo = Vector((min(v.co.x for v in vs), min(v.co.y for v in vs), min(v.co.z for v in vs)))
        hi = Vector((max(v.co.x for v in vs), max(v.co.y for v in vs), max(v.co.z for v in vs)))
        tgt = Vector(BS(*size))
        c = (lo + hi) / 2
        for v in vs:
            for i in range(3):
                ext = max(1e-6, hi[i] - lo[i])
                v.co[i] = (v.co[i] - c[i]) * (tgt[i] / ext)


def torso_upper(b, s):
    w, h, d = s
    b.rbox((0, -0.06, 0), (w * 0.88, h * 0.78, d * 0.92), BASE, bevel=0.08)        # chest
    b.rbox((0, h * 0.34, 0), (w, h * 0.22, d * 0.86), BASE, bevel=0.1)              # shoulder line
    b.rbox((0, -h * 0.38, 0), (w * 0.8, h * 0.24, d * 0.88), MID, bevel=0.06)       # waist band
    b.rbox((0, h * 0.46, 0.02), (w * 0.38, h * 0.08, d * 0.66), DARK, bevel=0.03)   # collar
    for sx in (-1, 1):
        b.rbox((sx * w * 0.2, h * 0.06, -d * 0.47), (w * 0.22, h * 0.22, 0.05), MID, bevel=0.015)  # chest pockets
        b.rbox((sx * w * 0.2, h * 0.17, -d * 0.48), (w * 0.22, 0.04, 0.05), DARK)
    b.rbox((0, 0, -d * 0.465), (0.03, h * 0.7, 0.02), DARK)                          # zip
    b.rbox((0, 0.05, d * 0.46), (w * 0.6, h * 0.5, 0.03), MID)                       # back panel
    b.ao(-h, h, 0.72, 1.0)


def torso_lower(b, s):
    w, h, d = s
    b.rbox((0, -0.05, 0), (w * 0.96, h * 0.8, d * 0.94), BASE, bevel=0.08)
    b.rbox((0, h * 0.3, 0), (w, h * 0.22, d), DEEP, bevel=0.02)                      # belt
    b.rbox((0, h * 0.3, -d * 0.5), (0.16, 0.12, 0.03), MID)                          # buckle
    for sx in (-1, 1):
        b.rbox((sx * w * 0.32, -0.02, -d * 0.47), (w * 0.2, h * 0.3, 0.03), MID)    # front pockets
    b.ao(-h, h, 0.7, 1.0)


def head(b, s):
    w, h, d = s
    r = w / 2
    b.rcyl((0, -h * 0.5, 0.02), (0, -h * 0.28, 0.02), r * 0.62, BALA, seg=12)        # neck
    b.rcyl((0, -h * 0.3, 0), (0, h * 0.22, 0), r * 0.98, BALA, r2=r, seg=14)         # skull
    b.rcyl((0, h * 0.22, 0), (0, h * 0.5, 0), r, BALA, r2=r * 0.45, seg=14)          # crown
    b.rbox((0, -h * 0.12, -d * 0.36), (w * 0.6, h * 0.22, d * 0.2), BALA, bevel=0.05)  # jaw/mouth area
    b.rbox((0, h * 0.06, -d * 0.43), (w * 0.62, h * 0.12, 0.06), SKIN, bevel=0.01)    # eye opening
    for sx in (-1, 1):
        b.rbox((sx * w * 0.15, h * 0.06, -d * 0.465), (w * 0.12, h * 0.05, 0.02), EYES)
    b.rbox((0, h * 0.13, -d * 0.44), (w * 0.64, h * 0.03, 0.05), BALA)               # brow seam


def upper_arm(b, s, side):
    w, h, d = s
    b.rcyl((0, h * 0.36, 0), (0, -h * 0.5, 0), w * 0.5, BASE, r2=w * 0.43, seg=10)
    b.rcyl((0, h * 0.36, 0), (0, h * 0.5, 0), w * 0.5, BASE, r2=w * 0.25, seg=10)   # shoulder cap
    b.rbox((side * w * 0.47, h * 0.12, 0), (0.04, h * 0.2, d * 0.46), MID, bevel=0.01)  # sleeve patch
