def foot(b, s, side):
    w, h, d = s
    b.rbox((0, -h * 0.36, 0), (w, h * 0.28, d), SOLE, bevel=0.02)                    # sole
    b.rbox((0, h * 0.06, d * 0.04), (w * 0.88, h * 0.62, d * 0.9), BOOT, bevel=0.05)  # upper
    b.rbox((0, -h * 0.02, -d * 0.4), (w * 0.84, h * 0.42, d * 0.16), BOOT2, bevel=0.04)  # toe cap
    b.rbox((0, h * 0.42, d * 0.3), (w * 0.8, h * 0.18, d * 0.34), BOOT2, bevel=0.02)  # collar


BUILD = {
    "UpperTorso": torso_upper, "LowerTorso": torso_lower, "Head": head,
    "UpperArm": upper_arm, "LowerArm": lower_arm, "Hand": hand,
    "UpperLeg": upper_leg, "LowerLeg": lower_leg, "Foot": foot,
}


def build(scene):
    col = scene.collection
    objs = []
    for name, part in SPEC["parts"].items():
        b = Seg("ZR_OP_" + name)
        s = part["size"]
        if name in BUILD:
            BUILD[name](b, s)
        else:
            side = 1 if name.startswith("Right") else -1
            BUILD[name[5:] if side == 1 else name[4:]](b, s, side)
        b.fit(s)
        objs.append(b.finish(col))
    return objs


scene = batch_scene("ZR_Operator")
objs = build(scene)
fbx, blend, meta = export_batch(objs, "ZR_Operator", scene)
